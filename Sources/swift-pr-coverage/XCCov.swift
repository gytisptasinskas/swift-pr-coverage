import Foundation
import PRCoverageCore

/// Wraps `xcrun xccov view --archive`.
enum XCCov {
    /// Absolute source paths recorded in the bundle.
    static func fileList(_ xcresult: String) throws -> [String] {
        let result = try xccov(["--file-list", xcresult], xcresult: xcresult)
        return String(decoding: result.stdout, as: UTF8.self)
            .split(separator: "\n")
            .map(String.init)
    }

    /// Per-line coverage of one file. `path` must be exactly as `fileList` returned it.
    static func coverage(ofFile path: String, in xcresult: String) throws -> CoverageMap {
        let result = try xccov(["--file", path, "--json", xcresult], xcresult: xcresult)
        return try CoverageParser.parse(result.stdout)
    }

    /// Per-line coverage of every file in the bundle.
    static func coverage(of xcresult: String) throws -> CoverageMap {
        let result = try xccov(["--json", xcresult], xcresult: xcresult)
        return try CoverageParser.parse(result.stdout)
    }

    private static func xccov(_ arguments: [String], xcresult: String) throws -> ProcessResult {
        let result = try Shell.run("xcrun", ["xccov", "view", "--archive"] + arguments)
        guard result.succeeded else {
            if result.stderr.contains("No coverage data in result bundle") {
                throw ToolError("""
                \(xcresult) has no coverage data. Enable code coverage on the scheme that ran the tests. \
                With Tuist, `tuist test` runs the <Name>-Workspace scheme: add a Workspace.swift with \
                `generationOptions: .options(autogeneratedWorkspaceSchemes: .enabled(codeCoverageMode: .relevant))`, \
                or run `tuist test -- -enableCodeCoverage YES`.
                """)
            }
            throw ToolError(command: "xccov view --archive \(arguments.joined(separator: " "))", result: result)
        }
        return result
    }
}
